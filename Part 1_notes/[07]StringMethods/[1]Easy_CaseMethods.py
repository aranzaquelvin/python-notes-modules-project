# Example 1: Changing Cases (Easy)
# upper(), lower(), title(), capitalize()
text = "hello python programming"

print("Original:", text)
print("Upper:", text.upper())       # LAHAT MALAKI
print("Title:", text.title())       # Bawat Salita Ay Malaki Ang Unang Letra
print("Capitalize:", text.capitalize()) # Yung unang letra lang ng sentence