# Example 5: join() Method (Intermediate)
# Pinagsasama yung listahan para maging isang string
letters = ["P", "y", "t", "h", "o", "n"]

# I-u-join sila gamit ang walang space
word = "".join(letters)
print("Joined word:", word)

# I-u-join sila gamit ang dash (-)
word_with_dash = "-".join(letters)
print("With dashes:", word_with_dash)