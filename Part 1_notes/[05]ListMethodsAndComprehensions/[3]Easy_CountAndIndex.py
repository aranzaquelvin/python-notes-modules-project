# Example 3: count() and index() methods (Easy)
# Para maghanap ng bagay sa listahan
grades = ["A", "B", "A", "C", "A", "B"]

# .count() - kung ilang beses lumabas
count_a = grades.count("A")
print(f"May {count_a} na 'A' sa listahan.")

# .index() - kung saan unang nakita
first_b_index = grades.index("B")
print(f"Ang unang 'B' ay nasa index {first_b_index}.")